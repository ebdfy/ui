// Generates what describes the package's API from its source: the custom-elements manifest, which
// the versioning test compares with the last release's, and the TypeScript declarations.
import { execFileSync } from 'node:child_process'
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import type { Manifest } from './versioning.ts'

const root = fileURLToPath(new URL('..', import.meta.url))
const bin = (name: string) => `${root}node_modules/.bin/${name}`

export const v2ManifestPath = `${root}dist/custom-elements-v2.json`
export const typesDir = `${root}dist/types`

export function generateTypes(): void {
  execFileSync(bin('tsc'), ['-p', 'tsconfig.types.json'], { cwd: root, stdio: 'pipe' })
}

// v2's e-* tags, from the JSDoc on their classes: @tag, @attr with its values, @fires, @slot. A tag
// that CSS alone draws has an `export declare class` for it, which emits no code.
export function generateV2Manifest(outFile = v2ManifestPath): Manifest {
  const dir = mkdtempSync(path.join(tmpdir(), 'ebdfy-v2-manifest-'))
  try {
    execFileSync(
      bin('cem'),
      ['analyze', '--globs', 'src/v2/**/*.ts', '--outdir', path.relative(root, dir), '--quiet'],
      {
        cwd: root,
        stdio: 'pipe',
      },
    )
    copyFileSync(`${dir}/custom-elements.json`, outFile)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
  // SAFETY: the analyzer has just written this file in the custom-elements manifest schema.
  return JSON.parse(readFileSync(outFile, 'utf8')) as Manifest
}

// What an attribute takes in JSX: its values when the JSDoc names them, else a string.
function jsxType(text: string | undefined): string {
  if (!text || text === 'string') return 'string'
  if (text === 'boolean') return 'boolean'
  if (text === 'number') return 'number | string'
  return text
}

// The declarations an app gets with @ebdfy/ui/v2 (each tag's class in HTMLElementTagNameMap) and
// with @ebdfy/ui/v2/react (each tag in React 19's JSX, with only its own attributes).
export interface V2Types {
  // HTMLElementTagNameMap, for @ebdfy/ui/v2.
  elements: string
  // React 19's JSX, for @ebdfy/ui/v2/react.
  react: string
}

export function v2Types(manifest: Manifest): V2Types {
  const tags = manifest.modules.flatMap((module) =>
    (module.declarations ?? [])
      .filter((d) => d.customElement && d.tagName)
      .map((d) => ({
        tag: d.tagName!,
        type: `import('./${module.path.replace(/^src\//, '').replace(/\.ts$/, '.js')}').${d.name}`,
        attributes: d.attributes ?? [],
      })),
  )
  const header = '// Generated by scripts/declarations.ts from the v2 custom-elements manifest.\n'
  const elements = `${header}export * from './v2.js'

declare global {
  interface HTMLElementTagNameMap {
${tags.map(({ tag, type }) => `    '${tag}': ${type}`).join('\n')}
  }
}
`
  const react = `${header}import type { DetailedHTMLProps, HTMLAttributes } from 'react'

import type {} from './v2-elements.js'

// A tag takes React's attributes for any element, its own in place of any of the same name, and nothing else.
type Tag<E extends HTMLElement, Own> = Omit<DetailedHTMLProps<HTMLAttributes<E>, E>, keyof Own> & Own

declare module 'react' {
  namespace JSX {
    interface IntrinsicElements {
${tags
  .map(({ tag, type, attributes }) => {
    const own = attributes.map(
      (a) => `${/^[a-z]\w*$/.test(a.name) ? a.name : `'${a.name}'`}?: ${jsxType(a.type?.text)}`,
    )
    return `      '${tag}': Tag<${type}, { ${own.join('; ')} }>`
  })
  .join('\n')}
    }
  }
}
`
  return { elements, react }
}

export function writeV2Types(manifest: Manifest): void {
  const { elements, react } = v2Types(manifest)
  writeFileSync(`${typesDir}/v2-elements.d.ts`, elements)
  writeFileSync(`${typesDir}/v2-react.d.ts`, react)
}
